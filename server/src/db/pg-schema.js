// Applies every migration that has not been applied yet, all inside one transaction guarded by an advisory lock,
// so two servers starting at the same moment cannot both migrate. (`pg_advisory_xact_lock` is transaction-level,
// so it also works through a pooled connection such as Neon's PgBouncer.) Never touches existing rows.
export async function runPgMigrations(db) {
  const applied = [];
  await db.transaction(async (tx) => {
    await tx.run('SELECT pg_advisory_xact_lock(7001, 1)');
    await tx.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
      version    INTEGER PRIMARY KEY,
      name       TEXT NOT NULL,
      applied_at TEXT NOT NULL
    )`);
    const done = new Set((await tx.all('SELECT version FROM schema_migrations')).map((r) => r.version));
    for (const m of migrations) {
      if (done.has(m.version)) continue;
      await tx.exec(m.sql);
      await tx.run('INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)', [
        m.version,
        m.name,
        new Date().toISOString(),
      ]);
      applied.push(m.version);
    }
  });
  return applied;
}
